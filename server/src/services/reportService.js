// src/services/reportService.js
'use strict';

const PDFDocument = require('pdfkit');
const Document = require('../models/Document');
const Analysis = require('../models/Analysis');
const { ForbiddenError, NotFoundError } = require('../middleware/errorHandler');

const DISCLAIMER = 'DISCLAIMER: This report is AI-generated for informational purposes only and does not constitute legal advice. Risk levels are informational indicators and do not determine the legal validity or enforceability of any clause.';

const generateReport = async (documentId, userId, res) => {
  const doc = await Document.findById(documentId).lean();
  if (!doc) throw new NotFoundError('Document not found');
  if (doc.userId.toString() !== userId.toString()) throw new ForbiddenError('Access denied');

  const analysis = await Analysis.findOne({ documentId, processingStatus: 'completed' }).lean();
  if (!analysis) throw new NotFoundError('Analysis not found. Please complete analysis before downloading a report.');

  const safeName = doc.originalFilename.replace(/[^a-zA-Z0-9._-]/g, '_');
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `attachment; filename="lexiclear-${safeName}.pdf"`);

  const pdf = new PDFDocument({ margin: 50, size: 'A4' });
  pdf.pipe(res);

  const sec = (title) => {
    pdf.moveDown(0.8);
    pdf.fontSize(13).fillColor('#1e3a5f').text(title, { underline: true });
    pdf.fontSize(10).fillColor('#333333').moveDown(0.3);
  };
  const txt = (text) => {
    const isEmpty = !text || text === 'Not specified in the document.';
    pdf.fontSize(10).fillColor(isEmpty ? '#999999' : '#333333').text(text || 'Not specified in the document.', { lineGap: 2 });
    pdf.moveDown(0.2);
  };

  // Header
  pdf.fontSize(20).fillColor('#1e3a5f').text('LexiClear', { align: 'center' });
  pdf.fontSize(11).fillColor('#4a6fa5').text('AI-Powered Legal Document Analysis Report', { align: 'center' });
  pdf.moveDown(0.3);
  pdf.fontSize(9).fillColor('#666').text(`Document: ${doc.originalFilename}`, { align: 'center' });
  pdf.text(`Generated: ${new Date().toLocaleString()}`, { align: 'center' });
  pdf.moveDown(0.8);
  pdf.moveTo(50, pdf.y).lineTo(545, pdf.y).stroke('#cccccc');
  pdf.moveDown(0.5);
  pdf.fontSize(8).fillColor('#cc0000').text(DISCLAIMER, { lineGap: 2 });

  sec('Overview'); txt(analysis.overview);
  sec('Detailed Summary'); txt(analysis.detailedSummary);

  if (analysis.sectionSummaries && analysis.sectionSummaries.length) {
    sec('Section-by-Section Summary');
    analysis.sectionSummaries.forEach((s, i) => {
      pdf.fontSize(10).fillColor('#2c5282').text(`${i + 1}. ${s.section || 'Section'}`);
      txt(s.summary);
    });
  }

  if (analysis.importantClauses && analysis.importantClauses.length) {
    sec('Important Clauses');
    analysis.importantClauses.forEach((c, i) => {
      pdf.fontSize(10).fillColor('#2c5282').text(`${i + 1}. ${c.title || 'Clause'}`);
      if (c.excerpt) pdf.fontSize(9).fillColor('#666').text(`"${c.excerpt}"`, { lineGap: 2 });
      txt(c.explanation);
    });
  }

  if (analysis.riskFindings && analysis.riskFindings.length) {
    sec('Potential Risk Findings');
    analysis.riskFindings.forEach((rf, i) => {
      const col = rf.riskLevel === 'High' ? '#cc0000' : rf.riskLevel === 'Medium' ? '#cc7700' : '#007700';
      pdf.fontSize(10).fillColor(col).text(`${i + 1}. [${rf.riskLevel || 'Low'}] ${rf.clauseTitle || 'Risk Finding'}`);
      pdf.fontSize(9).fillColor('#555').text(`Category: ${rf.riskCategory || 'Other'}`);
      if (rf.sourceExcerpt) pdf.fontSize(9).fillColor('#666').text(`"${rf.sourceExcerpt}"`, { lineGap: 2 });
      txt(rf.plainExplanation);
      if (rf.suggestedQuestion) pdf.fontSize(9).fillColor('#2c5282').text(`Suggested: ${rf.suggestedQuestion}`, { lineGap: 2 });
      pdf.moveDown(0.2);
    });
  }

  if (analysis.obligations && analysis.obligations.length) {
    sec('Rights and Obligations');
    analysis.obligations.forEach(o => pdf.fontSize(10).fillColor('#333').text(`- ${o.obligation} (${o.party || 'unspecified'})`, { lineGap: 2 }));
  }

  if (analysis.deadlines && analysis.deadlines.length) {
    sec('Deadlines and Notice Periods');
    analysis.deadlines.forEach(d => pdf.fontSize(10).fillColor('#333').text(`- ${d.description}: ${d.date || 'Not specified'}`, { lineGap: 2 }));
  }

  if (analysis.glossary && analysis.glossary.length) {
    sec('Legal Terminology Glossary');
    analysis.glossary.forEach(g => {
      pdf.fontSize(10).fillColor('#2c5282').text(g.term || '', { continued: true });
      pdf.fillColor('#333').text(`: ${g.definition || ''}`, { lineGap: 2 });
    });
  }

  pdf.moveDown(1.5);
  pdf.moveTo(50, pdf.y).lineTo(545, pdf.y).stroke('#cccccc');
  pdf.moveDown(0.4);
  pdf.fontSize(8).fillColor('#999').text('Generated by LexiClear AI - for informational purposes only.', { align: 'center' });
  pdf.end();
};

module.exports = { generateReport };
